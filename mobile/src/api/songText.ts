/**
 * Разбор названий песен с ютуба.
 *
 * Модуль чистый — ни сети, ни хранилища, ни React. Так он проверяется
 * без запуска приложения и годится и для api/ytmusic.ts (поиск обложек
 * и текстов), и для features/feed.ts (отсев уже слышанного).
 *
 * Раньше это жило внутри ytmusic.ts. Вынесено, когда понадобилось во
 * втором месте: список шумовых слов должен быть один, иначе две копии
 * разойдутся, и «то же самое» в двух частях приложения начнёт означать
 * разное.
 */

/**
 * Слова, которые ничего не говорят о песне.
 *
 * К названиям на ютубе приписывают всё это пачками, и при сравнении
 * они создают ложные совпадения: «official» есть в половине роликов.
 */
const NOISE = new Set([
  'official', 'video', 'audio', 'lyrics', 'lyric', 'music', 'mv', 'hd', 'hq',
  'remastered', 'version', 'feat', 'ft', 'prod', 'клип', 'клипец', 'текст',
  'премьера', 'песня',
]);

/**
 * Убрать приписку исполнителя в начале названия.
 *
 * На ютубе принято «Queen - We Will Rock You», но поле автора при этом
 * может быть каким угодно: у концертной записи там «Live Aid», у
 * перезалива — имя канала. Вычитание автора из названия такую приписку
 * не убирает, и одна песня даёт два разных отпечатка.
 *
 * Отрезаем только короткое начало — до четырёх значимых слов. Длинное
 * первое звено это уже часть названия, а не имя.
 */
function dropArtistPrefix(title: string): string {
  const match = title.match(/^(.{1,40}?)\s+[-–—|]\s+(.+)$/);
  if (!match) return title;

  const head = match[1].trim();
  const words = head.split(/\s+/).length;
  return words <= 4 ? match[2] : title;
}

/** Значимые слова строки: без пунктуации, скобок, шума и годов. */
export function tokens(value: string): Set<string> {
  return new Set(
    value
      .toLowerCase()
      .replace(/[([{].*?[)\]}]/g, ' ')
      .replace(/[^\p{L}\p{N}]+/gu, ' ')
      .split(' ')
      .filter((word) => word.length >= 3 && !NOISE.has(word) && !/^\d{4}$/.test(word)),
  );
}

/**
 * Отпечаток песни — чтобы узнать её в другой загрузке.
 *
 * Зачем. Одна и та же песня лежит на ютубе десятком роликов с разными
 * videoId: клип, аудиодорожка, концертная запись, чей-то перезалив.
 * Сверять «уже слышал» по videoId значит не узнать ни одну из них, и
 * в подсказках появляется то, что человек слушал вчера.
 *
 * Как. Из названия берём значимые слова и вычитаем имя исполнителя:
 * в заголовках его пишут то внутри («Queen - Don't Stop Me Now»), то
 * только в поле автора, и без вычитания одна и та же песня давала бы
 * два разных отпечатка. Исполнителя добавляем отдельно — первым словом
 * по алфавиту, чтобы «Queen» и «Queen Official» сошлись.
 *
 * Отпечатков два, и строгость у них разная — потому что задачи разные.
 *
 *   songTitleKey — только название. Им схлопывается выдача: две загрузки
 *   одной песни рядом в одной ленте выглядят поломкой, и убрать одну
 *   важнее, чем сохранить редкий кавер другого исполнителя.
 *
 *   songSignature — название плюс исполнитель. Им проверяется «уже
 *   слышал». Здесь ошибка дороже: лишнее совпадение прячет то, чего
 *   человек не слышал. Концертная запись у нас честно считается другой
 *   вещью, и это осознанно.
 */
export function songTitleKey(title: string, author: string): string {
  const byAuthor = tokens(author);
  const inTitle = tokens(dropArtistPrefix(title));

  const core = [...inTitle].filter((word) => !byAuthor.has(word));
  // Название целиком состоит из имени исполнителя — брать нечего,
  // оставляем как есть, иначе ключ станет пустым и совпадёт со всем.
  return (core.length > 0 ? core : [...inTitle]).sort().join(' ');
}

/**
 * Запоминание отпечатков.
 *
 * Отпечаток считается по журналу прослушиваний, а там одни и те же треки
 * встречаются десятками раз: у двадцати тысяч событий уникальных пар
 * «название + исполнитель» несколько сотен. Без кэша разбор строки шёл
 * на каждое событие заново, и пересчёт профиля вкуса упирался именно
 * в него — а профиль пересчитывается на каждой смене трека, в потоке
 * интерфейса.
 *
 * Потолок нужен, чтобы карта не росла бесконечно за долгую сессию.
 * При переполнении чистим целиком: выбирать, что выбросить, тут дороже,
 * чем посчитать заново.
 */
const SIGNATURE_LIMIT = 4000;
const signatureCache = new Map<string, string>();

export function songSignature(title: string, author: string): string {
  const key = `${title}\u0000${author}`;
  const cached = signatureCache.get(key);
  if (cached !== undefined) return cached;

  const who = [...tokens(author)].sort()[0] ?? '';
  const value = `${songTitleKey(title, author)}|${who}`;

  if (signatureCache.size >= SIGNATURE_LIMIT) signatureCache.clear();
  signatureCache.set(key, value);

  return value;
}

/**
 * Похоже ли найденное на то, что искали.
 *
 * Без этой проверки выдача принималась любая: на запрос из несуществующих
 * слов YouTube Music всё равно что-нибудь возвращает, и приложение
 * показывало чужую обложку и чужой текст, ничем не выдавая ошибки.
 *
 * Сравниваем по значимым словам, а не по строке целиком: у ролика
 * к названию приписано «(Клипец, 2020)», у аудиозаписи — нет,
 * и точного совпадения ждать нельзя никогда.
 */
export function looksLikeSame(query: string, found: string): boolean {
  const want = tokens(query);
  const got = tokens(found);
  if (want.size === 0 || got.size === 0) return false;

  let hits = 0;
  for (const word of got) if (want.has(word)) hits += 1;

  // Половина значимых слов найденного должна встречаться в запросе.
  // Одного слова мало: «Meant To Be» совпало бы с «Be Yourself».
  return hits / got.size >= 0.5;
}

/**
 * Имя исполнителя, пригодное для показа.
 *
 * В поле автора у ютуба лежит название канала, а не имя артиста:
 * «Queen Official», «ArtistVEVO», «Имя - Topic». В списке это терпимо —
 * там имя стоит под своей обложкой и читается по контексту. А вот в
 * предложении («по мотивам того, что вы слушаете — …») канал выглядит
 * нелепо, и «Live Aid and Queen Official» тому пример.
 *
 * Отрезаем только заведомо служебные хвосты. Угадывать дальше опасно:
 * у части исполнителей слово вроде Music — часть настоящего имени.
 */
const CHANNEL_TAIL = /\s*(?:[-–—]\s*Topic|VEVO|Official(?:\s+(?:Channel|Music|Video|Audio))?|Channel)\s*$/iu;

export function displayArtist(name: string): string {
  const clean = name.replace(CHANNEL_TAIL, '').trim();
  return clean.length > 0 ? clean : name.trim();
}

